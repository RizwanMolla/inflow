/** Bright accent tones, identical to ACCENT_COLORS[].hex in the desktop app. */
export const ACCENT_HEX: Record<AccentColor, string> = {
  indigo: '#818cf8',
  blue: '#60a5fa',
  cyan: '#22d3ee',
  emerald: '#34d399',
  amber: '#fbbf24',
  rose: '#fb7185',
  violet: '#a78bfa',
  slate: '#94a3b8',
};

/** Unknown colors (e.g. from a newer desktop build) fall back to indigo instead of crashing. */
export function getAccentHex(color?: AccentColor): string {
  return (color && ACCENT_HEX[color]) || ACCENT_HEX.indigo;
}

/** Library icons render as Lucide glyphs; anything else is treated as an emoji chosen on the PC. */
export function renderDeckIcon(iconName: string, size = 22, color = '#FFFFFF') {
  const IconComponent = ICONS_MAP[iconName];
  if (IconComponent) return <IconComponent size={size} color={color} />;
  if (iconName && !/^[A-Za-z0-9]+$/.test(iconName)) {
    return <Text style={{ fontSize: size * 0.95, lineHeight: size * 1.15 }}>{iconName}</Text>;
  }
  return <Zap size={size} color={color} />;
}
